#!/bin/bash
# make_stub.sh - generate a link-time stub library from ubgi.pas external
# symbols, so the ported Pascal code links cleanly.
#
# The ported BGI graphics unit (src/pascal/ubgi.pas) declares ~130 drawing
# symbols as `external 'siriel_bgi'`. The engine is headless and Raylib draws
# the real window, so those symbols are never really executed - we still
# need *something* to satisfy the linker. This script extracts every symbol
# from ubgi.pas and emits a tiny C stub (no-op bodies), then compiles it
# into a shared library placed in out/.
#
# Layout (this script lives in build/):
#   src/pascal/ubgi.pas - source of the symbol list
#   out/libsiriel_bgi.dylib(.so) - the generated stub
#   out/.stub.c, out/.stub.symbols - generated intermediates
set -euo pipefail

BUILD="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$BUILD/.." && pwd)"
PASCAL="$ROOT/src/pascal"
OUT="$ROOT/out"
mkdir -p "$OUT"
UBGI="${PASCAL}/ubgi.pas"
STUB_C="${OUT}/.stub.c"
SYMBOLS="${OUT}/.stub.symbols"

# macOS needs a .dylib; everything else uses the conventional .so.
case "$(uname -s)" in
  Darwin) STUB_SO="${OUT}/libsiriel_bgi.dylib" ;;
  *)      STUB_SO="${OUT}/libsiriel_bgi.so"  ;;
esac

if [[ ! -f "$UBGI" ]]; then
  echo "error: $UBGI not found" >&2
  exit 1
fi

# Extract symbol names. ubgi uses:  external LIB_UBGI name LIB_FNPFX + '<sym>';
# LIB_FNPFX is '' on Linux/Windows, so the bare C symbol is <sym>.
# Accept letters, digits, underscore and '$' (some siriel_bgi names contain it).
grep -oE "name LIB_FNPFX \+ '[A-Za-z0-9_]+'" "$UBGI" \
  | sed -E "s/.*'([A-Za-z0-9_]+)'/\1/" \
  | sort -u > "$SYMBOLS"

echo "extracted $(wc -l < "$SYMBOLS") symbols from $UBGI"

{
  echo "/* AUTO-GENERATED by build/make_stub.sh - do not edit. */"
  echo "/* BGI symbol stubs for the Siriel 3.5 FPC port. Rendering is done by"
  echo "   Raylib; these are link-time no-ops only. */"
  while read -r sym; do
    [[ -z "$sym" ]] && continue
    printf 'void %s(void) {}\n' "$sym"
  done < "$SYMBOLS"
} > "$STUB_C"

# Prefer gcc; fall back to clang (macOS Homebrew ships clang, not gcc).
if command -v gcc >/dev/null 2>&1; then CC=gcc
elif command -v clang >/dev/null 2>&1; then CC=clang
else echo "ERROR: need gcc or clang to build the stub library." >&2; exit 1; fi
# Install the stub with a location-independent install_name (@executable_path)
# so the engine records a runtime path that resolves next to the binary, rather
# than a hardcoded absolute path from wherever this script was first run.
$CC -shared -fPIC -O2 -install_name @executable_path/libsiriel_bgi.dylib -o "$STUB_SO" "$STUB_C"
echo "built $STUB_SO ($(wc -l < "$STUB_C") exports)"
